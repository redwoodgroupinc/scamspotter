import { buildSecurityHeaders } from "./headers";

/** Static hosts that read `_headers` (and, for Netlify, `_redirects`) from the output folder. */
export type StaticHost = "cloudflare" | "netlify";

const FORMAT_DOCS: Record<StaticHost, string> = {
  cloudflare: "https://developers.cloudflare.com/workers/static-assets/headers/",
  netlify: "https://docs.netlify.com/routing/headers/",
};

/**
 * Builds the `_headers` file for a static deployment. It applies the same
 * security headers that next.config.ts sends when the site runs on a Node
 * server, plus long-lived caching for Next.js's content-hashed files.
 *
 * On Cloudflare it also sends `noindex` on every *.workers.dev address
 * (production and preview URLs), so only the custom domain appears in search
 * results. Netlify already marks Deploy Previews and branch deploys `noindex`.
 */
export function buildHeadersFile({ adsEnabled, host }: { adsEnabled: boolean; host: StaticHost }): string {
  const security = buildSecurityHeaders({ adsEnabled, isDev: false, isPreview: false });
  const block = (pattern: string, headers: { key: string; value: string }[]) =>
    [pattern, ...headers.map(({ key, value }) => `  ${key}: ${value}`)].join("\n");

  return [
    "# Generated by scripts/build-static.mts. Do not edit by hand.",
    `# Format: ${FORMAT_DOCS[host]}`,
    "",
    block("/*", security),
    "",
    block("/_next/static/*", [{ key: "Cache-Control", value: "public, max-age=31536000, immutable" }]),
    "",
    ...(host === "cloudflare"
      ? [block("https://:worker.:subdomain.workers.dev/*", [{ key: "X-Robots-Tag", value: "noindex, nofollow" }]), ""]
      : []),
  ].join("\n");
}

/**
 * Builds Netlify's `_redirects` file. The static export writes each page as
 * `about.html` next to an `about/` folder of navigation data, so these
 * rewrites make sure `/about` always serves `about.html` (with a 200, not a
 * redirect) rather than depending on how the host resolves the folder.
 *
 * @param htmlFiles page files relative to the output folder, e.g. "guides/foo.html"
 */
export function buildNetlifyRedirects(htmlFiles: string[]): string {
  const rules = htmlFiles
    .map((file) => file.split("\\").join("/"))
    .filter(
      (file) =>
        file.endsWith(".html") &&
        file !== "index.html" &&
        !file.endsWith("/index.html") &&
        !/^(404|500|_not-found)\.html$/.test(file),
    )
    .sort()
    .map((file) => `/${file.slice(0, -".html".length)} /${file} 200`);
  return [
    "# Generated by scripts/build-static.mts. Do not edit by hand.",
    "# Format: https://docs.netlify.com/routing/redirects/",
    "",
    ...rules,
    "",
  ].join("\n");
}
