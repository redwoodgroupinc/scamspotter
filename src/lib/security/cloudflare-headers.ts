import { buildSecurityHeaders } from "./headers";

/**
 * Builds the `_headers` file used by Cloudflare static assets (Workers or
 * Pages). It applies the same security headers that next.config.ts sends
 * when the site runs on a Node server, plus:
 * - long-lived caching for Next.js's content-hashed files, and
 * - `noindex` on every *.workers.dev address (production and preview URLs),
 *   so only the custom domain appears in search results.
 */
export function buildCloudflareHeaders({ adsEnabled }: { adsEnabled: boolean }): string {
  const security = buildSecurityHeaders({ adsEnabled, isDev: false, isPreview: false });
  const block = (pattern: string, headers: { key: string; value: string }[]) =>
    [pattern, ...headers.map(({ key, value }) => `  ${key}: ${value}`)].join("\n");

  return [
    "# Generated by scripts/build-cloudflare.mts. Do not edit by hand.",
    "# Format: https://developers.cloudflare.com/workers/static-assets/headers/",
    "",
    block("/*", security),
    "",
    block("/_next/static/*", [{ key: "Cache-Control", value: "public, max-age=31536000, immutable" }]),
    "",
    block("https://:worker.:subdomain.workers.dev/*", [{ key: "X-Robots-Tag", value: "noindex, nofollow" }]),
    "",
  ].join("\n");
}
